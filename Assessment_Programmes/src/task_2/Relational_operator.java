package task_2;

public class Relational_operator {

	public static void main(String[] args) {
		int a = 10;
        int b = 20;

        System.out.println("a = " + a + ", b = " + b);

        // 1. Equal to (==)
        System.out.println("a == b : " + (a == b));

        // 2. Not equal to (!=)
        System.out.println("a != b : " + (a != b));

        // 3. Greater than (>)
        System.out.println("a > b  : " + (a > b));

        // 4. Less than (<)
        System.out.println("a < b  : " + (a < b));

        // 5. Greater than or equal to (>=)
        System.out.println("a >= b : " + (a >= b));

        // 6. Less than or equal to (<=)
        System.out.println("a <= b : " + (a <= b));
	}

}
